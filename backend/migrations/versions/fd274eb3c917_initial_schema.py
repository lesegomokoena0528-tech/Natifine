def _enum(*values, name):
    """Use native Postgres enums without creating them per table.

    Postgres enum types are shared by several tables (for example
    ``notificationchannel``). Creating them inline via ``op.create_table``
    would emit ``CREATE TYPE`` more than once and fail with
    ``DuplicateObject``. ``create_type=False`` keeps the column definition
    while ``_create_enums`` creates each type exactly once.
    """
    if op.get_bind().dialect.name == "postgresql":
        return postgresql.ENUM(*values, name=name, create_type=False)

    return sa.Enum(*values, name=name)


